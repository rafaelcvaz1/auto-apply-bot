import 'dotenv/config';
import { loadProfile, loadSources, dashboardPort } from './discovery/config.js';
import { Store } from './discovery/store.js';
import { createSearchServer } from './discovery/server.js';
loadSources();
const profile=loadProfile();
const store=new Store();
store.reassess(profile);
const server=createSearchServer(store,profile);
server.on('error',e=>{console.error('Não foi possível iniciar o painel:',e.message);store.close();process.exitCode=1;});
server.listen(dashboardPort(),'127.0.0.1',()=>console.log(`Painel local na porta ${dashboardPort()}. Busca e revisão apenas; candidaturas e mensagens desativadas.`));
for(const signal of ['SIGINT','SIGTERM'] as const) process.on(signal,()=>server.close(()=>{store.close();process.exit(0);}));
